def validation(key: str, **kw) -> None:
    dv = DataValidation(allow_blank=True, errorTitle="Periksa lagi", **kw)
    if TIPS[key]:
        dv.prompt, dv.showInputMessage = TIPS[key], True
    dv.add(rng(key))
