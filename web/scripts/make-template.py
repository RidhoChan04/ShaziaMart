def rng(key: str) -> str:
    return f"{COL[key]}{FIRST}:{COL[key]}{LAST}"


def abs_rng(key: str) -> str:
    return f"${COL[key]}${FIRST}:${COL[key]}${LAST}"


def barcode_ok(c: str) -> str:
    """TRUE when cell c holds a GTIN-14 / EAN-13 / UPC-A / EAN-8 code with a valid check digit."""
    ean13 = (
        f"MOD(10-MOD(SUMPRODUCT(--MID({c},{{1,3,5,7,9,11}},1))"
        f"+3*SUMPRODUCT(--MID({c},{{2,4,6,8,10,12}},1)),10),10)=VALUE(MID({c},13,1))"
    )
    upc12 = (
        f"MOD(10-MOD(3*SUMPRODUCT(--MID({c},{{1,3,5,7,9,11}},1))"
        f"+SUMPRODUCT(--MID({c},{{2,4,6,8,10}},1)),10),10)=VALUE(MID({c},12,1))"
    )
    ean8 = (
        f"MOD(10-MOD(3*SUMPRODUCT(--MID({c},{{1,3,5,7}},1))"
        f"+SUMPRODUCT(--MID({c},{{2,4,6}},1)),10),10)=VALUE(MID({c},8,1))"
    )
    gtin14 = (
        f"MOD(10-MOD(3*SUMPRODUCT(--MID({c},{{1,3,5,7,9,11,13}},1))"
        f"+SUMPRODUCT(--MID({c},{{2,4,6,8,10,12}},1)),10),10)=VALUE(MID({c},14,1))"
    )
    return (
        f"IFERROR(IF(LEN({c})=14,{gtin14},IF(LEN({c})=13,{ean13},IF(LEN({c})=12,{upc12},"
        f"IF(LEN({c})=8,{ean8},FALSE)))),FALSE)"
    )


def status_formula(r: int) -> str:
    c = {k: f"{v}{r}" for k, v in COL.items()}

    def used_elsewhere(cell: str) -> str:  # same barcode anywhere in either barcode column
        return (
            f'IF({cell}<>"",SUMPRODUCT(({abs_rng("barcode")}={cell})*1)'
            f'+SUMPRODUCT(({abs_rng("big_barcode")}={cell})*1)>1,FALSE)'
        )

    big_any = f'COUNTA({c["big_unit"]}:{c["big_price"]})>0'
    rules = [
        (f'{c["nama"]}=""', "Nama barang belum diisi"),
        (f'{c["nama"]}<>TRIM({c["nama"]})', "Ada spasi dobel di nama"),
        (f'SUMPRODUCT(({abs_rng("nama")}={c["nama"]})*1)>1', "Nama sama dengan baris lain"),
        (f'{c["unit"]}=""', "'Dijual per' belum diisi"),
        (f'{c["price"]}=""', "Harga jual belum diisi"),
        (f'AND({c["cost"]}<>"",{c["price"]}<{c["cost"]})', "Harga jual di bawah modal"),
        (f'AND({c["barcode"]}<>"",NOT({barcode_ok(c["barcode"])}))', "Barcode salah, scan ulang"),
        (used_elsewhere(c["barcode"]), "Barcode sudah dipakai barang lain"),
        (f'({c["tier_min"]}="")<>({c["tier_price"]}="")', "Grosir: isi 'beli minimal' dan harganya"),
        (f'AND({c["tier_price"]}<>"",{c["tier_price"]}>={c["price"]})', "Harga grosir harus lebih murah"),
        (f'AND({big_any},{c["big_unit"]}="")', "Satuan besar: nama satuan belum diisi"),
        (f'AND({big_any},{c["big_unit"]}={c["unit"]})', "Satuan besar sama dengan satuan eceran"),
        (f'AND({big_any},OR({c["big_size"]}="",{c["big_size"]}<2))', "Satuan besar: isi berapa? (min. 2)"),
        (f'AND({big_any},{c["big_price"]}="")', "Satuan besar: harga jual belum diisi"),
        (f'AND({c["big_cost"]}<>"",{c["big_price"]}<{c["big_cost"]})', "Satuan besar: harga jual di bawah modal"),
        (f'AND({c["big_barcode"]}<>"",NOT({barcode_ok(c["big_barcode"])}))', "Barcode satuan besar salah"),
        (used_elsewhere(c["big_barcode"]), "Barcode satuan besar sudah dipakai"),
    ]
    body = '"Lengkap"'
    for cond, msg in reversed(rules):
        body = f'IF({cond},"{msg}",{body})'
    return f'=IF(COUNTA({FIRST_INPUT}{r}:{LAST_INPUT}{r})=0,"",{body})'


def band(ws, group_cols: list, row: int) -> None:
    """Row-1 group titles merged over their columns."""
    for group, first, last in group_cols:
        label, colour = GROUPS[group]
        if first != last:
            ws.merge_cells(start_row=row, start_column=first, end_row=row, end_column=last)
        cell = ws.cell(row=row, column=first, value=label or None)
        cell.font = Font(name=FONT, bold=True, color="FFFFFF", size=10)
        cell.alignment = Alignment(horizontal="center", vertical="center")
        for col in range(first, last + 1):
            ws.cell(row=row, column=col).fill = PatternFill("solid", fgColor=colour)


def titles(ws, columns: list, row: int, first_col: int = 1, notes: bool = True) -> None:
    edge = Side(style="thin", color="FFFFFF")
    for i, (key, group, title, width, *_r, note, _tip) in enumerate(columns, start=first_col):
        cell = ws.cell(row=row, column=i, value=title)
        cell.font = Font(name=FONT, bold=True, color=INK)
        cell.fill = PatternFill("solid", fgColor="E9EEEB")
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = Border(left=edge, right=edge)
        if notes and note:
            cell.comment = Comment(note, "Petunjuk", width=330, height=120)
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.row_dimensions[row].height = 34


def group_spans(columns: list, first_col: int = 1) -> list:
    spans = []
    for i, (_key, group, *_r) in enumerate(columns, start=first_col):
        if spans and spans[-1][0] == group:
            spans[-1][2] = i
        else:
            spans.append([group, i, i])
    return spans


